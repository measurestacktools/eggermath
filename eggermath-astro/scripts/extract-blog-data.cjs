#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const blogDir = path.join(__dirname, '..', 'src', 'pages', 'blog');
const outFile = path.join(__dirname, '..', 'src', 'data', 'blog-posts.js');

const files = fs.readdirSync(blogDir)
  .filter(f => f.endsWith('.astro') && f !== 'index.astro' && !f.startsWith('['))
  .sort();

const posts = [];

for (const file of files) {
  const raw = fs.readFileSync(path.join(blogDir, file), 'utf-8');
  const slug = file.replace('.astro', '');

  // Extract post metadata from frontmatter (two patterns)
  let titleMatch = raw.match(/title:\s*['"](.+?)['"]/);
  let descMatch = raw.match(/desc:\s*['"](.+?)['"]/);
  let dateMatch = raw.match(/date:\s*['"](.+?)['"]/);
  let categoryMatch = raw.match(/category:\s*['"](.+?)['"]/);

  // Alternate pattern: const title = "..."; const description = "..."; (no post object)
  if (!titleMatch) titleMatch = raw.match(/const\s+title\s*=\s*["'](.+?)["']/);
  if (!descMatch) descMatch = raw.match(/const\s+description\s*=\s*["'](.+?)["']/);
  if (!dateMatch) dateMatch = raw.match(/const\s+date\s*=\s*["'](.+?)["']/);
  if (!categoryMatch) categoryMatch = raw.match(/const\s+category\s*=\s*["'](.+?)["']/);

  if (!titleMatch) {
    console.log(`SKIP: ${file} - no title found`);
    continue;
  }

  // Extract HTML body: try multiple patterns
  let body = '';

  // Pattern 1: Content inside BaseLayout tags
  const mainMatch = raw.match(/<BaseLayout[^>]*>\s*\n([\s\S]*?)\n\s*<\/BaseLayout>/);
  if (mainMatch) {
    body = mainMatch[1];
  }
  // Pattern 2: Content inside <article> tags
  if (!body) {
    const articleMatch = raw.match(/<article[^>]*>([\s\S]*?)<\/article>/);
    if (articleMatch) {
      body = articleMatch[1];
    }
  }
  // Pattern 3: Content inside <main> tags
  if (!body) {
    const mainAlt = raw.match(/<main[^>]*>([\s\S]*?)<\/main>/);
    if (mainAlt) {
      body = mainAlt[1];
    }
  }

  // Clean up the body: remove the "Back to Blog" link and date span (first 2 lines)
  body = body.replace(/^\s*<a href="\/blog"[^>]*>← Back to Blog<\/a>\s*\n\s*<span[^>]*>\{post\.date\}<\/span>\s*\n/, '');
  body = body.replace(/^\s*<a href="\/blog"[^>]*>← Back to Blog<\/a>\s*\n\s*<span[^>]*>[^<]*<\/span>\s*\n/, '');

  // Replace {post.title} with the actual title
  body = body.replace(/\{post\.title\}/g, titleMatch[1]);
  // Replace {post.desc} with actual description
  body = body.replace(/\{post\.desc\}/g, descMatch ? descMatch[1] : '');
  // Replace {post.date} with actual date
  body = body.replace(/\{post\.date\}/g, dateMatch ? dateMatch[1] : '');

  // Extract related posts if present
  let relatedPosts = [];
  const relatedPostsMatch = body.match(/Related Posts[\s\S]*?<ul[^>]*>([\s\S]*?)<\/ul>/);
  if (relatedPostsMatch) {
    const linkMatches = relatedPostsMatch[1].matchAll(/href="\/blog\/([^"]+)"[^>]*>([^<]+)</g);
    for (const m of linkMatches) {
      relatedPosts.push({ slug: m[1], title: m[2] });
    }
  }

  // Extract related games if present
  let relatedGames = [];
  const relatedGamesMatch = body.match(/Related Games[\s\S]*?<div[^>]*>([\s\S]*?)<\/div>\s*<\/div>/);
  if (relatedGamesMatch) {
    const gameMatches = relatedGamesMatch[1].matchAll(/href="\/([^"]+)"[^>]*>([^<]+)</g);
    for (const m of gameMatches) {
      if (!m[1].startsWith('blog/') && m[1] !== '') {
        relatedGames.push({ slug: m[1], name: m[2] });
      }
    }
  }

  // Remove the Related Posts and Related Games sections from body (they'll be rendered by the template)
  body = body.replace(/\n\s*<div[^>]*>\s*\n\s*<h2[^>]*>Related Posts<\/h2>[\s\S]*?<\/ul>\s*\n\s*<\/div>/, '');
  body = body.replace(/\n\s*<div[^>]*>\s*\n\s*<h3[^>]*>Related Games<\/h3>[\s\S]*?<\/div>\s*\n\s*<\/div>/, '');

  // Trim trailing whitespace
  body = body.trim();

  posts.push({
    slug,
    title: titleMatch[1],
    desc: descMatch ? descMatch[1] : '',
    date: dateMatch ? dateMatch[1] : '',
    category: categoryMatch ? categoryMatch[1] : 'Guides',
    body,
    relatedPosts,
    relatedGames,
  });

  console.log(`OK: ${slug} (${body.length} chars)`);
}

// Sort by date descending
posts.sort((a, b) => b.date.localeCompare(a.date));

// Generate the data file
const output = `// Auto-generated by scripts/extract-blog-data.cjs — do not edit manually
// To add a new blog post, create the .astro file and re-run: node scripts/extract-blog-data.cjs

export const blogPosts = ${JSON.stringify(posts, null, 2)};
`;

fs.writeFileSync(outFile, output, 'utf-8');
console.log(`\nWrote ${posts.length} posts to ${outFile}`);
